"""Generate docs/data_dictionary.md: every dbt model with its layer, materialization, grain
comment, columns with types (from the warehouse) and the tests attached to each column.

Inputs: a dbt manifest (default dbt/target/manifest.json or the newest found) and the
warehouse database from .env (read-only role). Run: python scripts/data_dictionary.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    from dataops.config import Role, load_dotenv
    from dataops.db import connect

    load_dotenv()
    manifests = sorted(
        (ROOT / "dbt" / "target").glob("**/manifest.json"), key=lambda p: p.stat().st_mtime
    )
    if not manifests:
        print("no dbt manifest; run dbt parse first", file=sys.stderr)
        return 1
    m = json.loads(manifests[-1].read_text())
    models = sorted(
        (n for n in m["nodes"].values() if n["resource_type"] == "model"),
        key=lambda n: (n["fqn"][1:-1], n["name"]),
    )
    tests: dict[tuple[str, str], list[str]] = {}
    for n in m["nodes"].values():
        if n["resource_type"] == "test" and n.get("column_name"):
            for dep in n["depends_on"]["nodes"]:
                if dep.startswith("model."):
                    name = (n.get("test_metadata") or {}).get("name") or "singular"
                    tests.setdefault((dep.split(".")[-1], n["column_name"]), []).append(name)
    with connect(Role.WH_READER, application_name="dataops-dictionary") as conn:
        cols: dict[str, list[tuple[str, str]]] = {}
        for t, c, typ in conn.execute(
            "select table_name, column_name, data_type from information_schema.columns"
            " where table_schema in ('staging','intermediate','marts')"
            " order by table_name, ordinal_position"
        ).fetchall():
            cols.setdefault(t, []).append((c, typ))
    out = [
        "# Data dictionary",
        "",
        "Generated by `python scripts/data_dictionary.py` from the dbt manifest and the warehouse",
        "catalog. Business definitions of the measures: [business_rules.md](business_rules.md);",
        "modeling decisions: [data_model.md](data_model.md). All data is synthetic.",
        "",
    ]
    for n in models:
        sql = (ROOT / "dbt" / n["original_file_path"]).read_text()
        header: list[str] = []
        for ln in sql.splitlines():
            if ln.startswith("--"):
                header.append(ln[2:].strip())
            elif header:
                break
        header = header[:6]
        layer = n["fqn"][1] if len(n["fqn"]) > 2 else "models"
        out += [
            f"## `{n['schema']}.{n['name']}`",
            "",
            f"Layer: {layer} · materialized: {n['config'].get('materialized')}"
            + (
                f" · unique key: `{n['config'].get('unique_key')}`"
                if n["config"].get("unique_key")
                else ""
            ),
            "",
        ]
        if header:
            out += [" ".join(header), ""]
        out += ["| Column | Type | Tests |", "|---|---|---|"]
        for c, typ in cols.get(n["name"], []):
            t = ", ".join(sorted(set(tests.get((n["name"], c), []))))
            out.append(f"| `{c}` | {typ} | {t} |")
        if n["name"] not in cols:
            out.append("| _(not built in the warehouse at generation time)_ | | |")
        out.append("")
    text = re.sub(r"\n{3,}", "\n\n", "\n".join(out))
    (ROOT / "docs" / "data_dictionary.md").write_text(text, encoding="utf-8")
    print(f"wrote docs/data_dictionary.md ({len(models)} models)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
