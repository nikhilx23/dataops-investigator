-- Ordered product change log, maintained transactionally by the source itself.
--
-- Why: SCD Type 2 history needs every intermediate version. Periodic batch extraction of
-- shop.products only sees the state at extraction time, so two price changes between runs
-- would lose the first. This log is written in the same transaction as each change, so the
-- batch path receives every version in order. (In the full profile, CDC provides the same
-- ordering from the WAL; this table keeps the lightweight profile honest without it.)

CREATE TABLE shop.product_versions (
    product_version_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          bigint      NOT NULL REFERENCES shop.products,
    version             integer     NOT NULL CHECK (version >= 1),
    sku                 text        NOT NULL,
    name                text        NOT NULL,
    category            text        NOT NULL,
    list_price_cents    bigint      NOT NULL CHECK (list_price_cents >= 0),
    is_active           boolean     NOT NULL,
    valid_from          timestamptz NOT NULL,  -- when the version took effect
    recorded_at         timestamptz NOT NULL,  -- when it was written to the log
    updated_at          timestamptz NOT NULL,  -- extraction cursor (rows are immutable)
    UNIQUE (product_id, version),
    UNIQUE (product_id, valid_from)
);
CREATE INDEX ON shop.product_versions (updated_at, product_version_id);

CREATE FUNCTION shop.log_product_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND
       (NEW.sku, NEW.name, NEW.category, NEW.list_price_cents, NEW.is_active)
         IS NOT DISTINCT FROM
       (OLD.sku, OLD.name, OLD.category, OLD.list_price_cents, OLD.is_active) THEN
        RETURN NULL;  -- no attribute change, no new version
    END IF;
    INSERT INTO shop.product_versions (product_id, version, sku, name, category,
                                       list_price_cents, is_active, valid_from, recorded_at,
                                       updated_at)
    SELECT NEW.product_id, COALESCE(MAX(v.version), 0) + 1, NEW.sku, NEW.name, NEW.category,
           NEW.list_price_cents, NEW.is_active, NEW.updated_at, clock_timestamp(),
           clock_timestamp()
    FROM shop.product_versions v WHERE v.product_id = NEW.product_id;
    RETURN NULL;
END $$;

-- AFTER trigger: runs once the BEFORE trigger has set updated_at.
CREATE TRIGGER products_log_version AFTER INSERT OR UPDATE ON shop.products
    FOR EACH ROW EXECUTE FUNCTION shop.log_product_version();
